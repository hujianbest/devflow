LANG_EXT = {
    ".java": "java", ".kt": "kotlin", ".py": "python", ".go": "go", ".rs": "rust", ".ts": "typescript",
    ".tsx": "typescript", ".js": "javascript", ".jsx": "javascript", ".c": "c", ".h": "c", ".cpp": "cpp",
    ".cc": "cpp", ".hpp": "cpp", ".cs": "csharp", ".rb": "ruby", ".php": "php", ".scala": "scala",
    ".swift": "swift", ".sql": "sql", ".proto": "protobuf", ".graphql": "graphql",
}
BUILD_ROOTS = {
    "package.json", "pom.xml", "build.gradle", "build.gradle.kts", "settings.gradle", "go.mod",
    "Cargo.toml", "pyproject.toml", "setup.py", "requirements.txt", "CMakeLists.txt", "Makefile",
    "build.sbt", "composer.json", "Gemfile", "*.csproj",
}
CONTRACT_PATTERNS = re.compile(r"(openapi|swagger|asyncapi).*\.(ya?ml|json)$|\.proto$|\.graphql$|\.avsc$|\.wsdl$", re.I)
MIGRATION_DIRS = {"migrations", "migration", "db/migrate", "flyway", "liquibase", "alembic"}
TEST_DIRS = {"test", "tests", "__tests__", "spec", "src/test"}
CI_FILES = {".gitlab-ci.yml", "Jenkinsfile", "azure-pipelines.yml", ".travis.yml"}
ENTRY_HINTS = re.compile(r"^(main|app|server|index|application|cmd)\.[a-z]+$|Application\.(java|kt)$", re.I)
EXCLUDE_DIRS = {".git", "node_modules", "dist", "build", "target", "vendor", ".venv", "venv", "__pycache__", ".idea", ".gradle", "out", "bin", "obj"}


def run_inventory(repo: Path, bundle: Path, name: str | None = None, max_files: int = 50000) -> dict:
    repo = repo.resolve()
    name = name or repo.name
    result: dict[str, Any] = {
        "repository": name,
        "path": str(repo),
        "scanned_at": dt.datetime.now().isoformat(timespec="seconds"),
        "git_head": _git_head(repo),
        "languages": {},
        "build_roots": [],
        "contracts": [],
        "migrations": [],
        "test_dirs": [],
        "ci": [],
        "containers": [],
        "codeowners": None,
        "entry_hints": [],
        "docs": [],
        "truncated": False,
        "unknown_extensions": {},
    }
    count = 0
    for dirpath, dirnames, filenames in os.walk(repo):
        dirnames[:] = sorted(d for d in dirnames if d not in EXCLUDE_DIRS and not d.startswith("."))
        rel_dir = Path(dirpath).relative_to(repo).as_posix()
        rel_dir = "" if rel_dir == "." else rel_dir
        if Path(dirpath).name in MIGRATION_DIRS or rel_dir in MIGRATION_DIRS:
            result["migrations"].append(rel_dir)
        if Path(dirpath).name in TEST_DIRS or rel_dir in TEST_DIRS:
            result["test_dirs"].append(rel_dir)
        for filename in filenames:
            count += 1
            if count > max_files:
                result["truncated"] = True
                break
            rel_path = f"{rel_dir}/{filename}" if rel_dir else filename
            ext = Path(filename).suffix.lower()
            lang = LANG_EXT.get(ext)
            if lang:
                result["languages"][lang] = result["languages"].get(lang, 0) + 1
            elif ext and ext not in (".md", ".txt", ".json", ".yml", ".yaml", ".xml", ".lock", ".png", ".jpg", ".svg"):
                result["unknown_extensions"][ext] = result["unknown_extensions"].get(ext, 0) + 1
            if filename in BUILD_ROOTS or filename.endswith(".csproj"):
                result["build_roots"].append(rel_path)
            if CONTRACT_PATTERNS.search(filename):
                result["contracts"].append(rel_path)
            if filename in CI_FILES or rel_dir.startswith(".github/workflows"):
                result["ci"].append(rel_path)
            if filename.startswith("Dockerfile") or filename in ("docker-compose.yml", "docker-compose.yaml"):
                result["containers"].append(rel_path)
            if filename == "CODEOWNERS":
                result["codeowners"] = rel_path
            if ENTRY_HINTS.search(filename):
                result["entry_hints"].append(rel_path)
            if ext == ".md" and (rel_dir.startswith("docs") or rel_dir.startswith("doc") or not rel_dir):
                result["docs"].append(rel_path)
        if result["truncated"]:
            break
    result["file_count"] = min(count, max_files)
    out_dir = bundle / ".kb" / "inventory"
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / f"{name}.json").write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")
    return result


def _git_head(repo: Path) -> str | None:
    head = repo / ".git" / "HEAD"
    if not head.is_file():
        return None
    ref = head.read_text(encoding="utf-8").strip()
    if ref.startswith("ref: "):
        ref_path = repo / ".git" / ref[5:]
        if ref_path.is_file():
            return ref_path.read_text(encoding="utf-8").strip()
        packed = repo / ".git" / "packed-refs"
        if packed.is_file():
            for line in packed.read_text(encoding="utf-8").splitlines():
                if line.endswith(" " + ref[5:]):
                    return line.split()[0]
        return None
    return ref


