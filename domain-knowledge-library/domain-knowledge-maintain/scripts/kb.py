def find_bundle_root(start: Path | None = None) -> Path | None:
    """Resolve the bundle root: env, .domain-kb pointer, ./domain-kb, or cwd."""
    env = os.environ.get("DOMAIN_KB_ROOT")
    if env and (Path(env) / "knowledge").is_dir():
        return Path(env).resolve()
    base = (start or Path.cwd()).resolve()
    pointer = base / ".domain-kb"
    if pointer.is_file():
        target = (base / pointer.read_text(encoding="utf-8").strip()).resolve()
        if (target / "knowledge").is_dir():
            return target
    for candidate in (base / "domain-kb", base):
        if (candidate / "knowledge" / "index.md").is_file() or (candidate / ".kb").is_dir():
            return candidate
    return None


def require_bundle(path_arg: str | None) -> Path:
    root = Path(path_arg).resolve() if path_arg else find_bundle_root()
    if root is None or not (root / "knowledge").is_dir():
        sys.exit("bundle root not found; pass --bundle or run kb.py init")
    return root


