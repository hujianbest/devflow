class ParseError(ValueError):
    pass


def split_frontmatter(text: str) -> tuple[str | None, str]:
    if not text.startswith("---\n"):
        return None, text
    end = text.find("\n---", 4)
    if end == -1:
        raise ParseError("unterminated frontmatter")
    return text[4:end], text[end + 4 :].lstrip("\n")


def _strip_comment(line: str) -> str:
    if '"' in line or "'" in line:
        return line
    return re.sub(r"\s#.*$", "", line)


def _scalar(raw: str) -> Any:
    value = raw.strip()
    if value in ("", "~", "null"):
        return None
    if value.startswith("[") and value.endswith("]"):
        inner = value[1:-1].strip()
        if not inner:
            return []
        return [_scalar(part) for part in re.split(r",\s*", inner)]
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    if value == "true":
        return True
    if value == "false":
        return False
    return value


def _split_kv(s: str) -> tuple[str, str]:
    match = re.match(r"^([A-Za-z0-9_.-]+):(?:\s+(.*))?$", s)
    if not match:
        raise ParseError(f"cannot parse mapping line: {s!r}")
    return match.group(1), (match.group(2) or "")


def parse_yaml_subset(text: str) -> dict:
    lines = [_strip_comment(l.rstrip()) for l in text.splitlines()]
    lines = [l for l in lines if l.strip() and not l.strip().startswith("#")]
    pos = 0

    def indent_of(line: str) -> int:
        return len(line) - len(line.lstrip(" "))

    def parse_block(indent: int) -> Any:
        nonlocal pos
        result: Any = None
        while pos < len(lines):
            line = lines[pos]
            cur = indent_of(line)
            if cur < indent:
                break
            if cur > indent:
                raise ParseError(f"unexpected indent: {line!r}")
            stripped = line.strip()
            if stripped.startswith("- ") or stripped == "-":
                if result is None:
                    result = []
                if not isinstance(result, list):
                    raise ParseError(f"mixed list and mapping at: {line!r}")
                item = stripped[1:].strip()
                pos += 1
                if item and re.match(r"^[A-Za-z0-9_.-]+:(\s|$)", item):
                    key, value = _split_kv(item)
                    entry: dict = {}
                    if value == "":
                        if pos < len(lines) and indent_of(lines[pos]) > indent + 2:
                            entry[key] = parse_block(indent_of(lines[pos]))
                        else:
                            entry[key] = None
                    else:
                        entry[key] = _scalar(value)
                    if pos < len(lines) and indent_of(lines[pos]) == indent + 2:
                        more = parse_block(indent + 2)
                        if isinstance(more, dict):
                            entry.update(more)
                    result.append(entry)
                else:
                    result.append(_scalar(item))
            else:
                if result is None:
                    result = {}
                if not isinstance(result, dict):
                    raise ParseError(f"mixed list and mapping at: {line!r}")
                key, value = _split_kv(stripped)
                pos += 1
                if value == "":
                    if pos < len(lines) and indent_of(lines[pos]) > indent:
                        result[key] = parse_block(indent_of(lines[pos]))
                    else:
                        result[key] = None
                else:
                    result[key] = _scalar(value)
        return result if result is not None else {}

    parsed = parse_block(0)
    if not isinstance(parsed, dict):
        raise ParseError("frontmatter must be a mapping")
    return parsed


def read_concept(path: Path) -> tuple[dict | None, str]:
    text = path.read_text(encoding="utf-8", errors="ignore")
    if text.startswith(GENERATED_MARK):
        return None, text
    fm_text, body = split_frontmatter(text)
    if fm_text is None:
        return None, body
    return parse_yaml_subset(fm_text), body


