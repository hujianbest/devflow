def run_proposals(bundle: Path, queue: bool = False) -> tuple[list[dict], list[str]]:
    proposals_dir = bundle / ".kb" / "proposals"
    queue_dir = bundle / ".kb" / "review-queue"
    items: list[dict] = []
    errors: list[str] = []
    if not proposals_dir.is_dir():
        return items, errors
    for path in sorted(proposals_dir.glob("*.md")):
        try:
            fm, body = read_concept(path)
        except ParseError as exc:
            errors.append(f"{path.name}: {exc}")
            continue
        if fm is None:
            errors.append(f"{path.name}: missing frontmatter")
            continue
        kind = fm.get("kind")
        if kind not in PROPOSAL_KINDS:
            errors.append(f"{path.name}: invalid kind `{kind}`")
        concepts = fm.get("concepts") or []
        if kind != "new" and not concepts:
            errors.append(f"{path.name}: `{kind}` proposal must list affected concepts")
        for c in concepts:
            if not (bundle / "knowledge" / str(c)).is_file():
                errors.append(f"{path.name}: concept not found: {c}")
        sources = fm.get("sources") or []
        if not sources:
            errors.append(f"{path.name}: proposal needs at least one source")
        for i, s in enumerate(sources):
            if not isinstance(s, dict) or s.get("role") not in ROLES:
                errors.append(f"{path.name}: sources[{i}] invalid role")
        if not re.search(r"^(Observed|Derived|Confirmed|Inferred)\b", body, re.MULTILINE):
            errors.append(f"{path.name}: body must mark claims as Observed/Derived/Confirmed/Inferred")
        queued = False
        if queue and kind in QUEUE_KINDS:
            queue_dir.mkdir(parents=True, exist_ok=True)
            target = queue_dir / path.name
            if not target.exists():
                target.write_text(
                    f"---\nkind: {kind}\nproposal: .kb/proposals/{path.name}\nqueued_at: {dt.datetime.now().isoformat(timespec='seconds')}\n---\n\n"
                    f"来自提案 `{path.name}`：{kind} 说明 Bundle 正在误导，需 Owner 处理。\n",
                    encoding="utf-8",
                )
            queued = True
        items.append({"file": path.name, "kind": kind, "concepts": concepts, "queued": queued})
    return items, errors


