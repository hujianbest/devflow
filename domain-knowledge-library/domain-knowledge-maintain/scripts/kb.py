def _index_body(text: str) -> str:
    """Strip the generation timestamp line so comparisons are stable."""
    return "\n".join(l for l in text.splitlines() if not l.startswith("生成于 "))


def _table(rows: list[tuple[str, dict]], base: str) -> list[str]:
    lines = ["| 路径 | type | 摘要 | status | view | owner |", "|---|---|---|---|---|---|"]
    for path, fm in rows:
        link = os.path.relpath(path, base) if base else path
        lines.append(
            "| [{p}]({l}) | {t} | {d} | {s} | {v} | {o} |".format(
                p=path,
                l=link,
                t=fm.get("type", ""),
                d=str(fm.get("description", "")).replace("|", "\\|"),
                s=fm.get("status", ""),
                v=fm.get("view", ""),
                o=fm.get("owner", ""),
            )
        )
    return lines


def build_indexes(bundle: Path, concepts: dict[str, dict]) -> dict[Path, str]:
    knowledge = bundle / "knowledge"
    stamp = dt.date.today().isoformat()
    groups: dict[str, list[tuple[str, dict]]] = {}
    for path, fm in sorted(concepts.items()):
        parts = path.split("/")
        group = "/".join(parts[:2]) if parts[0] in ("domains", "systems") and len(parts) > 2 else parts[0]
        groups.setdefault(group, []).append((path, fm))

    out: dict[Path, str] = {}
    root_lines = [GENERATED_MARK, "# Knowledge Index", "", f"生成于 {stamp}，由 `kb.py index` 维护，请勿手改。", ""]
    counts = {s: 0 for s in STATUSES}
    for fm in concepts.values():
        if fm.get("status") in counts:
            counts[fm["status"]] += 1
    root_lines.append(f"共 {len(concepts)} 条：draft {counts['draft']} · stable {counts['stable']} · deprecated {counts['deprecated']}。`draft` 可用但必须标明未确认；`deprecated` 不参与默认回答。")
    root_lines.append("")
    for group, rows in groups.items():
        root_lines.append(f"## {group}")
        root_lines.append("")
        root_lines.extend(_table(rows, ""))
        root_lines.append("")
        if group.count("/") == 1:
            sub_lines = [GENERATED_MARK, f"# {group}", "", f"生成于 {stamp}，由 `kb.py index` 维护，请勿手改。", ""]
            sub_lines.extend(_table(rows, group))
            sub_lines.append("")
            out[knowledge / group / "index.md"] = "\n".join(sub_lines)
    out[knowledge / "index.md"] = "\n".join(root_lines)
    return out


def run_index(bundle: Path) -> list[Path]:
    errors, _, concepts = run_validate(bundle)
    fatal = [e for e in errors if "frontmatter" in e]
    if fatal:
        sys.exit("\n".join(fatal))
    written = []
    for path, text in build_indexes(bundle, concepts).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        written.append(path)
    return written


