def validate_concept(knowledge: Path, path: Path, today: dt.date) -> tuple[list[str], list[str], dict | None]:
    errors: list[str] = []
    warnings: list[str] = []
    where = rel(knowledge, path)

    if not KEBAB.match(path.name):
        errors.append(f"{where}: file name must be kebab-case .md")

    try:
        fm, body = read_concept(path)
    except ParseError as exc:
        return [f"{where}: frontmatter parse error: {exc}"], warnings, None
    if fm is None:
        return [f"{where}: missing frontmatter"], warnings, None

    for field in REQUIRED_FIELDS:
        if fm.get(field) in (None, "", []):
            errors.append(f"{where}: missing required field `{field}`")

    ctype = fm.get("type")
    if ctype and ctype not in ALL_TYPES:
        errors.append(f"{where}: unknown type `{ctype}`")
    status = fm.get("status")
    if status and status not in STATUSES:
        errors.append(f"{where}: invalid status `{status}`")
    view = fm.get("view")
    if view and view not in VIEWS:
        errors.append(f"{where}: invalid view `{view}`")

    sources = fm.get("sources") or []
    if not isinstance(sources, list):
        errors.append(f"{where}: `sources` must be a list")
        sources = []
    for i, source in enumerate(sources):
        if not isinstance(source, dict):
            errors.append(f"{where}: sources[{i}] must be a mapping")
            continue
        resource = source.get("resource")
        role = source.get("role")
        if not resource:
            errors.append(f"{where}: sources[{i}] missing `resource`")
        elif str(resource).startswith("git+") and "@" not in str(resource):
            errors.append(f"{where}: sources[{i}] git resource must pin a revision with @<rev>")
        if role not in ROLES:
            errors.append(f"{where}: sources[{i}] invalid role `{role}`")

    verified = fm.get("verified") or []
    if verified and not isinstance(verified, list):
        errors.append(f"{where}: `verified` must be a list")
        verified = []
    verifiers = [str(v.get("by", "")) for v in verified if isinstance(v, dict)]

    if status == "stable":
        if not verifiers:
            errors.append(f"{where}: stable requires non-empty `verified`")
        elif ctype in HUMAN_VERIFIED_TYPES and not any(v.startswith("human:") for v in verifiers):
            errors.append(f"{where}: stable {ctype} requires a `human:` verifier")
    if fm.get("generated") and not verifiers and status == "stable":
        errors.append(f"{where}: generated concept without `verified` cannot be stable")

    if ctype in DETAIL_TYPES and not fm.get("expanded_by"):
        errors.append(f"{where}: detail type `{ctype}` requires `expanded_by` (only domain-knowledge-expand may create it)")

    if status == "deprecated" and not fm.get("superseded_by"):
        warnings.append(f"{where}: deprecated without `superseded_by`")

    superseded = fm.get("superseded_by")
    if superseded and not (knowledge / str(superseded)).is_file():
        errors.append(f"{where}: superseded_by target not found: {superseded}")

    stale_after = fm.get("stale_after")
    if stale_after:
        try:
            if dt.date.fromisoformat(str(stale_after)) < today:
                warnings.append(f"{where}: past stale_after {stale_after}")
        except ValueError:
            errors.append(f"{where}: stale_after must be YYYY-MM-DD")

    expected_dir = TYPE_DIR.get(ctype)
    if expected_dir and path.parent.name != expected_dir:
        warnings.append(f"{where}: type `{ctype}` usually lives under `{expected_dir}/`")
    if ctype in ("Bounded Context", "Application") and path.name != "overview.md":
        warnings.append(f"{where}: `{ctype}` is usually the directory's overview.md")

    for target in LINK.findall(body):
        if "://" in target or target.startswith(("#", "mailto:")):
            continue
        link_path = target.split("#", 1)[0]
        if link_path and not (path.parent / link_path).resolve().exists():
            errors.append(f"{where}: broken link {target}")

    return errors, warnings, fm


def detect_supersession_cycles(knowledge: Path, concepts: dict[str, dict]) -> list[str]:
    errors: list[str] = []
    graph = {p: str(fm.get("superseded_by")) for p, fm in concepts.items() if fm.get("superseded_by")}
    for start in graph:
        seen = [start]
        node = graph.get(start)
        while node:
            if node in seen:
                errors.append(f"{start}: superseded_by cycle via {' -> '.join(seen + [node])}")
                break
            seen.append(node)
            node = graph.get(node)
    return errors


def run_validate(bundle: Path, check_index: bool = False, today: dt.date | None = None) -> tuple[list[str], list[str], dict[str, dict]]:
    today = today or dt.date.today()
    knowledge = bundle / "knowledge"
    errors: list[str] = []
    warnings: list[str] = []
    concepts: dict[str, dict] = {}
    for path in iter_concepts(knowledge):
        e, w, fm = validate_concept(knowledge, path, today)
        errors.extend(e)
        warnings.extend(w)
        if fm is not None:
            concepts[rel(knowledge, path)] = fm
    errors.extend(detect_supersession_cycles(knowledge, concepts))
    if check_index:
        for index_path, expected in build_indexes(bundle, concepts).items():
            current = index_path.read_text(encoding="utf-8") if index_path.is_file() else ""
            if _index_body(current) != _index_body(expected):
                errors.append(f"{rel(knowledge, index_path)}: out of date, run `kb.py index`")
    return errors, warnings, concepts


