def run_audit(bundle: Path) -> tuple[Path, bool]:
    errors, warnings, concepts = run_validate(bundle, check_index=True)
    stale = run_stale(bundle)
    proposals, proposal_errors = run_proposals(bundle)
    queue_dir = bundle / ".kb" / "review-queue"
    queue = sorted(p.name for p in queue_dir.glob("*.md")) if queue_dir.is_dir() else []
    lock = read_lock(bundle)
    today = dt.date.today().isoformat()
    lines = [
        f"# Audit {today}",
        "",
        f"- Concepts: {stale['total']}（draft {stale['by_status']['draft']} · stable {stale['by_status']['stable']} · deprecated {stale['by_status']['deprecated']}）",
        f"- Errors: {len(errors)}",
        f"- Warnings: {len(warnings)}",
        f"- Past stale_after: {len(stale['stale'])}",
        f"- Pending proposals: {len(proposals)}（invalid {len(proposal_errors)}）",
        f"- Review queue: {len(queue)}",
        f"- Maintenance lock: {'held by ' + str(lock.get('holder')) if lock else 'free'}",
        "",
        "## Errors（回 ingest 修结构）",
        "",
    ]
    lines += [f"- {e}" for e in errors] or ["- none"]
    lines += ["", "## Warnings", ""]
    lines += [f"- {w}" for w in warnings] or ["- none"]
    lines += ["", "## Stale", ""]
    lines += [f"- {s['path']} (stale_after {s['stale_after']}, {s['status']})" for s in stale["stale"]] or ["- none"]
    lines += ["", "## Proposals", ""]
    lines += [f"- {p['file']} [{p['kind']}] → {', '.join(p['concepts']) or '(new)'}" for p in proposals] or ["- none"]
    lines += [f"- INVALID {e}" for e in proposal_errors]
    lines += ["", "## Review queue（回 review 裁语义）", ""]
    lines += [f"- {q}" for q in queue] or ["- none"]
    lines += ["", "## 需人工检查（脚本不判断）", "", "- 未标记 Inferred 的推断", "- AS-IS / TO-BE / historical 混写", "- 同名术语被强制合并", "- 冲突被静默覆盖", "- 敏感材料进入发布层", "- 黄金问题回归（设计场景 / 实现场景）", ""]
    out_dir = bundle / ".kb" / "audit"
    out_dir.mkdir(parents=True, exist_ok=True)
    report = out_dir / f"{today}.md"
    report.write_text("\n".join(lines), encoding="utf-8")
    append_log(bundle, "audit", f"errors={len(errors)} warnings={len(warnings)} stale={len(stale['stale'])} proposals={len(proposals)}")
    return report, not errors and not proposal_errors


def lock_path(bundle: Path) -> Path:
    return bundle / ".kb" / "maintenance.lock"


def read_lock(bundle: Path) -> dict:
    path = lock_path(bundle)
    if not path.is_file():
        return {}
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return {"holder": "unknown"}


def run_lock(bundle: Path, mode: str, holder: str) -> None:
    lock_path(bundle).parent.mkdir(parents=True, exist_ok=True)
    lock_path(bundle).write_text(
        json.dumps({"mode": mode, "holder": holder, "at": dt.datetime.now().isoformat(timespec="seconds")}, ensure_ascii=False),
        encoding="utf-8",
    )


def run_unlock(bundle: Path) -> bool:
    path = lock_path(bundle)
    if path.is_file():
        path.unlink()
        return True
    return False


def append_log(bundle: Path, mode: str, title: str) -> None:
    log = bundle / "knowledge" / "log.md"
    log.parent.mkdir(parents=True, exist_ok=True)
    if not log.is_file():
        log.write_text("# Log\n\n追加式记录。格式：`## [date] mode | 标题`。\n", encoding="utf-8")
    with log.open("a", encoding="utf-8") as fh:
        fh.write(f"\n## [{dt.date.today().isoformat()}] {mode} | {title}\n")


