def run_stale(bundle: Path, today: dt.date | None = None) -> dict:
    today = today or dt.date.today()
    _, _, concepts = run_validate(bundle, today=today)
    stale = []
    for path, fm in concepts.items():
        value = fm.get("stale_after")
        try:
            if value and dt.date.fromisoformat(str(value)) < today:
                stale.append({"path": path, "stale_after": str(value), "status": fm.get("status")})
        except ValueError:
            continue
    by_status = {s: sum(1 for fm in concepts.values() if fm.get("status") == s) for s in STATUSES}
    return {"total": len(concepts), "by_status": by_status, "stale": stale}


