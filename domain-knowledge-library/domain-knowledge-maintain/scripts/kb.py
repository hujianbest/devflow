def iter_concepts(knowledge: Path):
    for path in sorted(knowledge.rglob("*.md")):
        if path.name in SKIP_NAMES:
            continue
        yield path


def rel(knowledge: Path, path: Path) -> str:
    return path.relative_to(knowledge).as_posix()


