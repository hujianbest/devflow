def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="kb.py", description=__doc__)
    parser.add_argument("--bundle", help="bundle root (default: discover)")
    sub = parser.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("init", help="scaffold a bundle");
    p.add_argument("path"); p.add_argument("--name")
    p = sub.add_parser("validate", help="check concepts against bundle-contract");
    p.add_argument("--check-index", action="store_true"); p.add_argument("--json", action="store_true")
    sub.add_parser("index", help="rebuild index.md files")
    p = sub.add_parser("stale", help="list past stale_after and status counts"); p.add_argument("--json", action="store_true")
    p = sub.add_parser("proposals", help="list and validate .kb/proposals");
    p.add_argument("--queue", action="store_true", help="copy route-error/stale into review-queue"); p.add_argument("--json", action="store_true")
    p = sub.add_parser("inventory", help="static repository inventory into .kb/inventory");
    p.add_argument("repo"); p.add_argument("--name"); p.add_argument("--max-files", type=int, default=50000)
    sub.add_parser("audit", help="full check, write .kb/audit/<date>.md")
    p = sub.add_parser("lock", help="take the maintenance lock so hooks allow writes to knowledge/");
    p.add_argument("mode", choices=["bootstrap", "ingest", "sync", "review", "audit", "expand"]); p.add_argument("--holder", default=os.environ.get("USER", "agent"))
    sub.add_parser("unlock", help="release the maintenance lock")
    p = sub.add_parser("log", help="append a log.md entry"); p.add_argument("mode"); p.add_argument("title")

    args = parser.parse_args(argv)

    if args.cmd == "init":
        bundle = Path(args.path).resolve()
        (bundle / "knowledge").mkdir(parents=True, exist_ok=True)
        created = run_init(bundle, args.name)
        for path in created:
            print(f"created {path.relative_to(bundle)}")
        print(f"bundle ready at {bundle}")
        return 0

    bundle = require_bundle(args.bundle)

    if args.cmd == "validate":
        errors, warnings, concepts = run_validate(bundle, check_index=args.check_index)
        if args.json:
            print(json.dumps({"errors": errors, "warnings": warnings, "concepts": len(concepts)}, ensure_ascii=False, indent=2))
        else:
            for w in warnings:
                print(f"WARN  {w}")
            for e in errors:
                print(f"ERROR {e}")
            print(f"{len(concepts)} concepts, {len(errors)} errors, {len(warnings)} warnings")
        return 1 if errors else 0

    if args.cmd == "index":
        for path in run_index(bundle):
            print(f"wrote {path.relative_to(bundle)}")
        return 0

    if args.cmd == "stale":
        report = run_stale(bundle)
        if args.json:
            print(json.dumps(report, ensure_ascii=False, indent=2))
        else:
            print(f"total {report['total']} · " + " · ".join(f"{k} {v}" for k, v in report["by_status"].items()))
            for s in report["stale"]:
                print(f"STALE {s['path']} ({s['stale_after']}, {s['status']})")
        return 0

    if args.cmd == "proposals":
        items, errors = run_proposals(bundle, queue=args.queue)
        if args.json:
            print(json.dumps({"proposals": items, "errors": errors}, ensure_ascii=False, indent=2))
        else:
            for item in items:
                flag = " → review-queue" if item["queued"] else ""
                print(f"{item['file']} [{item['kind']}] {', '.join(item['concepts']) or '(new)'}{flag}")
            for e in errors:
                print(f"ERROR {e}")
            print(f"{len(items)} proposals, {len(errors)} errors")
        return 1 if errors else 0

    if args.cmd == "inventory":
        result = run_inventory(Path(args.repo), bundle, args.name, args.max_files)
        print(json.dumps({k: result[k] for k in ("repository", "git_head", "file_count", "languages", "build_roots", "contracts", "migrations", "truncated")}, ensure_ascii=False, indent=2))
        print(f"written to .kb/inventory/{result['repository']}.json")
        return 0

    if args.cmd == "audit":
        report, ok = run_audit(bundle)
        print(report.read_text(encoding="utf-8"))
        print(f"report: {report.relative_to(bundle)}")
        return 0 if ok else 1

    if args.cmd == "lock":
        existing = read_lock(bundle)
        if existing:
            print(f"lock already held by {existing.get('holder')} ({existing.get('mode')}, {existing.get('at')})")
            return 1
        run_lock(bundle, args.mode, args.holder)
        print(f"locked for {args.mode} by {args.holder}")
        return 0

    if args.cmd == "unlock":
        print("unlocked" if run_unlock(bundle) else "no lock held")
        return 0

    if args.cmd == "log":
        append_log(bundle, args.mode, args.title)
        print("logged")
        return 0

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
