class TestCapturePrompt(HookCase):
    def read_draft(self):
        run_hook("kb_read_guard.py", self.payload(tool_name="Read", tool_input={"path": str(self.draft)}), self.bundle)

    def test_prompts_once_when_reads_without_proposal(self):
        self.read_draft()
        out = run_hook("kb_capture_prompt.py", self.payload(status="completed", loop_count=0), self.bundle)
        self.assertIn("followup_message", out)
        self.assertIn("refund-limit.md", out["followup_message"])
        again = run_hook("kb_capture_prompt.py", self.payload(status="completed", loop_count=0), self.bundle)
        self.assertEqual(again, {})

    def test_silent_when_proposal_written(self):
        self.read_draft()
        run_hook("kb_write_guard.py", self.payload(tool_name="Write", tool_input={"path": str(self.bundle / ".kb" / "proposals" / "p.md"), "contents": "Observed  x"}), self.bundle)
        out = run_hook("kb_capture_prompt.py", self.payload(status="completed", loop_count=0), self.bundle)
        self.assertEqual(out, {})

    def test_silent_when_nothing_read_or_aborted_or_looping(self):
        self.assertEqual(run_hook("kb_capture_prompt.py", self.payload(status="completed", loop_count=0), self.bundle), {})
        self.read_draft()
        self.assertEqual(run_hook("kb_capture_prompt.py", self.payload(status="aborted", loop_count=0), self.bundle), {})
        self.assertEqual(run_hook("kb_capture_prompt.py", self.payload(status="completed", loop_count=1), self.bundle), {})

    def test_silent_during_maintenance(self):
        self.read_draft()
        self.lock()
        self.assertEqual(run_hook("kb_capture_prompt.py", self.payload(status="completed", loop_count=0), self.bundle), {})


class TestInstall(HookCase):
    def test_install_merges_hooks_json_and_copies_scripts(self):
        target = self.tmp / "repo"
        (target / ".cursor").mkdir(parents=True)
        (target / ".cursor" / "hooks.json").write_text(json.dumps({"version": 1, "hooks": {"stop": [{"command": "echo other"}]}}), encoding="utf-8")
        proc = subprocess.run(["bash", str(HOOKS / "install.sh"), str(target)], capture_output=True, text=True, check=False)
        self.assertEqual(proc.returncode, 0, proc.stderr)
        merged = json.loads((target / ".cursor" / "hooks.json").read_text(encoding="utf-8"))
        stop_commands = [e["command"] for e in merged["hooks"]["stop"]]
        self.assertIn("echo other", stop_commands)
        self.assertTrue(any("domain-kb/kb_capture_prompt.py" in c for c in stop_commands))
        self.assertTrue((target / ".cursor" / "hooks" / "domain-kb" / "kb_common.py").is_file())
        proc = subprocess.run(["bash", str(HOOKS / "install.sh"), str(target)], capture_output=True, text=True, check=False)
        merged = json.loads((target / ".cursor" / "hooks.json").read_text(encoding="utf-8"))
        self.assertEqual(sum("domain-kb/" in e["command"] for e in merged["hooks"]["stop"]), 1)


